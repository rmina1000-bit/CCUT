def from_model(count=50):
    """다른 모델이 쓴다 — 우리 상상력 밖의 말이 여기서 나온다."""
    from engine import hub
    out = []
    per = max(1, count // len(FLAVORS))
    for i, flavor in enumerate(FLAVORS):
        for k in range(per):
            n = 4 + ((i + k) % 5)
            try:
                d = hub._ollama_json(
                    MODEL_PROMPT.format(n=n, flavor=flavor),
                    timeout=90, temperature=1.0, model="qwen2.5:7b-instruct")
            except Exception as e:
                print(f"  [{i}.{k}] 실패: {e}")
                continue
            turns = [str(t)[:200] for t in (d.get("turns") or []) if str(t).strip()]
            if len(turns) < 2:
                continue
            out.append({"persona": str(d.get("persona") or flavor)[:40],
                        "source": "model", "flavor": flavor, "turns": turns})
            print(f"  [{len(out):3}] {out[-1]['persona'][:20]:20} {len(turns)}턴 "
                  f"· {turns[0][:34]!r}")
            if len(out) >= count:
                return out
    return out


def main():
    scen = [{"persona": p, "source": "human", "flavor": "", "turns": t}
            for p, t in HUMAN]
    print(f"사람이 쓴 것: {len(scen)}개 · {sum(len(s['turns']) for s in scen)}턴")
    print("모델이 쓰는 중…")
    scen += from_model(50)
    for i, s in enumerate(scen, 1):
        s["id"] = i
    total = sum(len(s["turns"]) for s in scen)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(scen, f, ensure_ascii=False, indent=1)
    print(f"\n전체 {len(scen)}시나리오 · {total}턴 → {OUT}")


if __name__ == "__main__":
    main()
